def expand_query(query: str) -> str:
    """Append every synonym / ontology group that shares a term with the query."""
    q = query.lower().replace("ё", "е")
    extra = [" ".join(g) for g in SYNONYMS if any(t in q for t in g)]
    for terms in ONTOLOGY.values():
        if any(t.replace("ё", "е") in q for t in terms):
            extra.append(" ".join(terms))
    return " ".join([query, *extra])
